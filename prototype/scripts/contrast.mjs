// S5: WCAG 2.2 AA contrast check of every text / token pair used in the app. Reads the tokens from
// src/styles/main.css, writes a11y/contrast.md, exits 1 if any pair fails.
// Text needs 4.5:1 (all our text is < 24 px regular / < 18.7 px bold except the big numbers, which we
// still hold to 4.5). Non-text UI (bars, outlines, focus ring, chart line) needs 3:1.
import fs from "node:fs";
const css = fs.readFileSync(new URL("../src/styles/main.css", import.meta.url), "utf8");
const tok = Object.fromEntries([...css.matchAll(/--([\w-]+):\s*(#[0-9a-fA-F]{3,6})/g)].map((m) => [m[1], m[2].toLowerCase()]));
const hex = (h) => { h = h.replace("#", ""); if (h.length === 3) h = [...h].map((c) => c + c).join(""); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255); };
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const L = (h) => { const [r, g, b] = hex(h).map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [L(a), L(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const v = (n) => (n.startsWith("#") ? n : tok[n]);
// backgrounds text sits on (tokens + the few literal hover/pressed fills used in components)
const BG = { "color-bg": "color-bg", "color-surface": "color-surface", "color-surface-2": "color-surface-2", "hover #202023": "#202023", "chip/pressed #303036": "#303036" };
const rows = [];
const add = (kind, fg, bg, use, min) => rows.push({ kind, fg, bg, use, r: ratio(v(fg), v(bg)), min });
for (const fg of ["text-primary", "text-secondary", "text-tertiary"]) for (const [bn, b] of Object.entries(BG)) add("text", fg, b, `${fg} on ${bn}`, 4.5);
add("text", "color-on-action", "color-action", "primary buttons, selected chips", 4.5);
add("text", "#3a3a40", "color-action", "serving grams inside a selected unit chip", 4.5);
add("text", "color-on-action", "shade-on-target", "calendar day number, on target", 4.5);
add("text", "color-on-action", "shade-close", "calendar day number, ±10 %", 4.5);
add("text", "text-primary", "shade-off", "calendar day number, ±20 %", 4.5);
add("text", "text-primary", "shade-far", "calendar day number, >20 %", 4.5);
add("text", "text-secondary", "color-surface", "calendar \"no target\" day number", 4.5);
add("text", "chart-line", "color-surface", "chart legend text in blue", 4.5);
add("ui", "color-progress", "color-track", "progress bar fill vs track", 3);
add("ui", "color-hit", "color-track", "on-target bar fill vs track", 3);
add("ui", "color-track", "color-surface", "bar track vs card (decorative; the fill carries the info)", 1);
add("ui", "chart-line", "color-surface", "trend line", 3);
add("ui", "color-border-strong", "color-surface", "outlined chips, unit chips, \"no target\" cell", 3);
add("ui", "color-border-strong", "color-surface-2", "inputs inside sheets", 3);
add("ui", "text-tertiary", "color-surface", "dashed outlines (over tag, hints, no-log cell)", 3);
add("ui", "text-secondary", "color-surface", "S8 low-accuracy dot on a card", 3);
add("ui", "text-secondary", "color-bg", "S8 low-accuracy dot in the sidebar", 3);
add("ui", "text-secondary", "color-surface-2", "S8 low-accuracy dot in the weight sheet stats", 3);
add("ui", "color-action", "color-bg", "focus ring on background", 3);
add("ui", "color-action", "color-surface", "focus ring on cards", 3);
add("ui", "color-action", "color-surface-2", "focus ring on sheets/fields", 3);
const fails = rows.filter((r) => r.r < r.min);
const fmt = (r) => `| ${r.kind} | \`${r.fg}\` ${v(r.fg)} | \`${r.bg}\` ${v(r.bg)} | ${r.use} | **${r.r.toFixed(2)}:1** | ${r.min}:1 | ${r.r >= r.min ? "pass" : "FAIL"} |`;
const md = `# Contrast check (WCAG 2.2 AA)

Generated by \`node scripts/contrast.mjs\` from \`src/styles/main.css\` on ${new Date().toISOString().slice(0, 10)}.
Text 4.5:1, non-text UI 3:1. Disabled controls (opacity .35) are exempt under WCAG and not listed.

| kind | foreground | background | where | ratio | needs | result |
|---|---|---|---|---|---|---|
${rows.map(fmt).join("\n")}

**${rows.length - fails.length} of ${rows.length} pass.**
`;
fs.writeFileSync(new URL("../a11y/contrast.md", import.meta.url), md);
console.log(md);
if (fails.length) process.exit(1);
